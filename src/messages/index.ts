export function isLocale(value: string | undefined): value is Locale {
  return locales.some((locale) => locale === value);
}

export function translate(locale: Locale, key: string): string {
  const localized = copy[locale] as Record<string, string>;
  const fallback = copy.it as Record<string, string>;
  return localized[key] ?? fallback[key] ?? key;
}

export function categoryMessageKey(name: string): string | undefined {
  const normalized = name.trim().toLocaleLowerCase("it");
  const keys: Record<string, string> = {
    auto: "category.auto",
    camion: "category.truck",
    moto: "category.moto",
    cucina: "category.kitchen",
    viaggi: "category.travel",
    musica: "category.music",
    gaming: "category.gaming",
    decorazione: "category.decor",
  };
  return keys[normalized];
}

